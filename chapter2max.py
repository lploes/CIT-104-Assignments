# Python program to find the max of five numbers
num1 = 40  # numbers 1 through 5 are the numbers the program will look through
num2 = 50
num3 = 20
num4 = 10
num5 = 30
largest = max(num1, num2, num3, num4, num5)  # numbers together
print(f"the max of {num1}, {num2}, {num3}, {num4}, and {num5} is {largest}")